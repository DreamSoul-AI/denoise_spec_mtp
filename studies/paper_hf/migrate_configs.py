"""Generate the paper_hf Studies and spec presets from configs/hf/ (manual tool).

    python studies/paper_hf/migrate_configs.py           # rewrite generated files
    python studies/paper_hf/migrate_configs.py --check   # exit 1 if anything is stale

configs/hf/<family>/<group>/<cell>.yaml stays as the record. Each family and
group becomes one Study per task (esp_mtp cells, ar_baseline, alignment_probe;
the two temperature-1 ablations get their own Study because their eval block
differs). The spec block of every esp_mtp / alignment_probe cell becomes a
named preset ``<model group>/<cell>`` in
src/spec_mtp/structure/algorithm/paper_variants.py, selected with
``algorithm.config.variant``. Nothing here adds a cell, a value or a sweep.
"""

from __future__ import annotations

import argparse
import json
import pprint
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
CONFIGS = ROOT / 'configs' / 'hf'
OUT = ROOT / 'studies' / 'paper_hf'
PRESETS = ROOT / 'src' / 'spec_mtp' / 'structure' / 'algorithm' / 'paper_variants.py'
GROUP = {'llama3_1_8b': 'llama3', 'llama3_2_3b': 'llama3', 'qwen3_8b': 'qwen3', 'qwen3_32b': 'qwen3'}
TEMPLATE = ROOT / 'studies' / '_template'


def load_cells():
    cells = []
    for path in sorted(CONFIGS.glob('*/*/*.yaml')):
        family, group = path.parts[-3], path.parts[-2]
        cfg = yaml.safe_load(path.read_text(encoding='utf-8'))
        cells.append({'path': path.relative_to(ROOT).as_posix(), 'family': family, 'group': group,
                      'cell': path.stem, 'cfg': cfg})
    return cells


def study_key(cell):
    task = cell['cfg']['run']['algorithm']
    suffix = {'esp_mtp': 'main' if cell['group'] == 'run_0' else 'ablations',
              'ar_baseline': 'ar_baseline', 'alignment_probe': 'alignment_probe'}[task]
    if task == 'esp_mtp' and float(cell['cfg']['eval'].get('temperature', 0.0)) != 0.0:
        suffix += '_temp' + str(cell['cfg']['eval']['temperature']).replace('.', 'p')
    return f"{cell['family']}_{suffix}"


def preset_name(cell):
    return f"{GROUP[cell['family']]}/{cell['cell']}"


def shared_blocks(cell):
    cfg = cell['cfg']
    data = dict(cfg['data'])
    model = dict(cfg['model'])
    eval_cfg = dict(cfg['eval'])
    assert model.pop('type') == 'hf_causal'
    eval_cfg.pop('device', None)  # the Run device comes from system.config.device
    return {
        'data': {'name': data.pop('name'), 'source': 'spec_mtp', 'config': data},
        'model': {'name': 'hf_causal', 'source': 'spec_mtp', 'config': model},
        'algorithm': {'mode': 'eval', 'source': 'spec_mtp',
                      'config': {'task': cfg['run']['algorithm'], 'eval': eval_cfg}},
        'system': {'config': {'device': 'cuda', 'deterministic': bool(cfg['run'].get('deterministic', False))}},
    }


def build():
    cells = load_cells()
    studies, presets = {}, {}
    for cell in cells:
        task = cell['cfg']['run']['algorithm']
        if task != 'ar_baseline':
            name = preset_name(cell)
            spec = cell['cfg']['spec']
            if name in presets and presets[name] != spec:
                raise ValueError(f'preset {name} differs between families')
            presets[name] = spec
        key = study_key(cell)
        blocks = shared_blocks(cell)
        entry = studies.setdefault(key, {'blocks': blocks, 'cells': [], 'seed': cell['cfg']['run']['seed']})
        if json.dumps(entry['blocks'], sort_keys=True) != json.dumps(blocks, sort_keys=True):
            raise ValueError(f'{cell["path"]} does not share the fixed blocks of Study {key}')
        if entry['seed'] != cell['cfg']['run']['seed']:
            raise ValueError(f'{cell["path"]} seed differs')
        entry['cells'].append(cell)
    files = {}
    for key, entry in sorted(studies.items()):
        root = OUT / key
        task = entry['blocks']['algorithm']['config']['task']
        study = {
            'study': f'paper_hf_{key}',
            'description': f'migrated from configs/hf ({len(entry["cells"])} cell(s)); GPU, not run here',
            'experiment': {'name': key},
            'recipe': 'recipe.py',
            'flow': {'study_phases': True, 'prepare_shared': False},
            'fixed': entry['blocks'],
        }
        if task == 'ar_baseline':
            study['axes'] = {}
        else:
            study['axes'] = {'algorithm.config.variant': [preset_name(c) for c in entry['cells']]}
        study['seeds'] = [entry['seed']]
        study['run_description'] = '{variant} seed={seed}' if task != 'ar_baseline' else 'ar_baseline seed={seed}'
        header = ('# Generated by studies/paper_hf/migrate_configs.py from:\n'
                  + ''.join(f'#   {c["path"]}\n' for c in entry['cells'])
                  + '# GPU Study: not run in CI or on CPU. Edit configs/hf and regenerate, or edit here and drop the\n'
                  + '# generator check in tests/spec_mtp/test_paper_hf.py.\n')
        files[root / 'study.yaml'] = header + yaml.safe_dump(study, sort_keys=False, allow_unicode=True)
        files[root / 'experiment_config.yaml'] = yaml.safe_dump({
            'experiment': key, 'description': 'base; study.yaml fixed carries the migrated blocks',
            'seed': entry['seed'],
            'data': {'name': entry['blocks']['data']['name'], 'source': 'spec_mtp'},
            'model': {'name': 'hf_causal', 'source': 'spec_mtp'},
            'algorithm': {'mode': 'eval', 'source': 'spec_mtp', 'config': {'task': task}},
            'system': {'config': {'device': 'cuda'}},
        }, sort_keys=False)
        files[root / 'recipe.py'] = (TEMPLATE / 'recipe.py').read_text(encoding='utf-8')
        for phase in ('write', 'process'):
            for name in ('__init__.py', 'run.py'):
                files[root / 'flow' / phase / name] = (TEMPLATE / 'flow' / phase / name).read_text(encoding='utf-8')
        rows = '\n'.join(f'| `{preset_name(c) if task != "ar_baseline" else "-"}` | `{c["path"]}` |' for c in entry['cells'])
        files[root / 'docs' / 'PLAN.md'] = f"""# PLAN — paper_hf/{key}

由 `configs/hf/` 迁移（2026-10-12），只换承载方式，不改格子和取值。论文对照见 [README.md](../../../../README.md) 的 Config → Paper Map，读法差异见 [ARCHITECTURE.md](../../../../docs/ARCHITECTURE.md)。

**状态：未运行。** 需要 GPU 和权重（`{entry['blocks']['model']['config']['name_or_path']}`，HF Hub，`local_files_only: false`）。CPU / CI 只验证展开和配置校验（`tests/spec_mtp/test_paper_hf.py`），不加载权重。

## 判定

1. `exact_match_rate` 必须是 1（write 门；bf16 下可能不成立，见 history_extrapolation 对 Qwen3-8B bf16 的记录）。
2. 主指标是接受的 draft 数；速度和 `tau` 不决定结论。

## 格子

| **variant** | **来源** |
| --- | --- |
{rows}

固定：seed {entry['seed']}，`deterministic: false`，`system.config.device: cuda`（原 YAML 的 `eval.device: auto` 由 Run 设备代替）。

## 怎么跑

```text
set PYTHONUTF8=1
python -m spec_mtp make studies/paper_hf/{key}
studies/paper_hf/{key}/scripts/launch.ps1
```

开跑前补 §3 排班与时长预估（RPipe `studies/README.md`）。
"""
    lines = ['"""Spec presets migrated from configs/hf/ (generated by studies/paper_hf/migrate_configs.py).',
             '',
             'Keys are ``<model group>/<cell>``; values are the YAML ``spec`` blocks verbatim.',
             'Selected by ``algorithm.config.variant``; see ``config_bridge.apply_variant``.',
             '"""', '', 'PAPER_VARIANTS = ' + pprint.pformat(dict(sorted(presets.items())), width=100, sort_dicts=False), '']
    files[PRESETS] = '\n'.join(lines)
    return files, studies


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files, studies = build()
    stale = [p for p, text in files.items() if not p.is_file() or p.read_text(encoding='utf-8') != text]
    if args.check:
        for path in stale:
            print('stale:', path.relative_to(ROOT))
        return 1 if stale else 0
    for path in stale:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(files[path], encoding='utf-8')
        print('wrote', path.relative_to(ROOT))
    print(f'{len(studies)} Studies')
    return 0


if __name__ == '__main__':
    sys.exit(main())
